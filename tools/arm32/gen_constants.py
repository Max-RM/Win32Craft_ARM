#!/usr/bin/env python3
"""Generate win32_host_arm32.h from the verified area facts (arm32/facts/*.json).

Every numeric `arm_rva` (hex) becomes `#define ARM_<AREA>_<ID> 0x........` (even code address; call code with
ARM_CODE(), which ORs in the Thumb bit).  `expected_bytes` become `static const BYTE ..._EXPECTED[]` arrays.
Nothing is transcribed by hand, so the header cannot drift from the facts; re-run after editing facts."""
import re, sys, os, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

# fmod_ARM.dll facts describe a different image (handled by the patcher, not by the host DLL); they are never emitted here.
SKIP_AREAS = ("fmod",)

ap = argparse.ArgumentParser(description="Generate a win32_host_arm32*.h constants header from verified area facts")
ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "win32_host_arm32.h"))
ap.add_argument("--facts", help="facts directory (default: arm32/facts = Minecraft 1.2.8; e.g. arm32/v1_16_40/facts)")
ap.add_argument("--prefix", default="ARM", help="macro prefix (default ARM; second game version e.g. ARM116)")
ap.add_argument("--guard", default="WIN32_HOST_ARM32_H")
ap.add_argument("--title", default="Minecraft 1.2.8 ARM32")
args = ap.parse_args()
if args.facts:
    os.environ["ARM32_FACTS_DIR"] = os.path.abspath(args.facts)
OUT, PREFIX, GUARD, TITLE = args.out, args.prefix, args.guard, args.title
from facts_survey import all_facts, rva_format


def cname(area, fid):
    base = fid[len(area) + 1:] if fid.startswith(area + ".") else fid
    s = re.sub(r"[^0-9A-Za-z]+", "_", area + "_" + base).strip("_").upper()
    return PREFIX + "_" + s


def one_line(s, n=96):
    s = " ".join(str(s or "").split())
    s = s.replace("*/", "* /")
    return s[:n]


lines = []
w = lines.append
w("/* %s - GENERATED by tools/arm32/gen_constants.py from the area facts (%s). DO NOT EDIT." % (os.path.basename(OUT), os.path.relpath(os.environ.get("ARM32_FACTS_DIR", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "arm32", "facts")), os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))))
w(" *")
w(" * %s (Thumb-2) image-relative constants, all verified by independent review." % TITLE)
w(" * RVAs are relative to the image base.  Code RVAs are EVEN: call/store function pointers with")
w(" * %s_CODE(image, rva) so the Thumb bit is set.  Data/IAT/vtable-cell RVAs are plain addresses." % PREFIX)
w(" * Pointer values stored in game data cells carry the Thumb bit (+1). */")
w("#ifndef %s" % GUARD)
w("#define %s" % GUARD)
w("")
w("#define %s_CODE(image, rva) ((void *)((BYTE *)(image) + (SIZE_T)(rva) + 1u))" % PREFIX)
w("#define %s_DATA(image, rva) ((void *)((BYTE *)(image) + (SIZE_T)(rva)))" % PREFIX)
w("")
seen = {}
cur = None
count = 0
for area, f in all_facts():
    if area in SKIP_AREAS:
        continue
    r = f.get("arm_rva")
    exp = f.get("expected_bytes")
    has_rva = rva_format(r) in ("hex", "int")
    exp_ok = isinstance(exp, str) and re.fullmatch(r"(?:[0-9a-fA-F]{2}[ ]?)+", exp.strip() or "x") is not None
    if not has_rva and not exp_ok:
        continue
    if area != cur:
        w("")
        w("/* ---- %s ---- */" % area)
        cur = area
    name = cname(area, f["id"])
    if name in seen:
        name += "_%d" % seen[name]
        seen[name] = 1
    seen[name] = seen.get(name, 0) + 1
    if has_rva:
        val = r if isinstance(r, str) else "0x%x" % r
        w("#define %-52s %-12s /* %s: %s */" % (name, val, f.get("kind"), one_line(f.get("summary"))))
        count += 1
    if exp_ok:
        hexs = re.sub(r"\s+", "", exp.strip())
        arr = ",".join("0x" + hexs[i:i + 2].lower() for i in range(0, len(hexs), 2))
        w("static const BYTE %s_EXPECTED[%d] = { %s };" % (name, len(hexs) // 2, arr))
w("")
w("#endif /* %s */" % GUARD)
text = "\r\n".join(lines) + "\r\n"
open(OUT, "wb").write(text.encode("utf-8"))
print("wrote", os.path.abspath(OUT), "constants:", count, "bytes:", len(text))
